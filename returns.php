<p>We want you to love what you buy. If something is wrong with your order, this policy explains what we will do.</p>

<h2>1. Returns within 7 days</h2>
<p>You can return a product within <strong>7 days of delivery</strong> if it is unused, unopened and still sealed in its original packaging.
For hygiene reasons we cannot accept products that have been opened, used or had their seal broken, unless they are faulty.</p>

<h2>2. Damaged, faulty or wrong items</h2>
<p>If your order arrives damaged, faulty, expired or is not what you ordered, please contact us within <strong>48 hours of delivery</strong>
with your order number and a photo of the item. We will replace it or refund you in full, including the delivery fee, and arrange collection at no cost to you.</p>

<h2>3. How to return an item</h2>
<ol>
    <li>Message us on WhatsApp or email with your order number and the reason for the return.</li>
    <li>We will confirm whether the item qualifies and arrange how to send it back.</li>
    <li>Once we receive and check the item, we will let you know and process your refund or replacement.</li>
</ol>
<p>For change-of-mind returns, the cost of sending the item back is paid by you.</p>

<h2>4. Refunds</h2>
<ul>
    <li>Approved refunds are paid back through <strong>Paystack</strong> to the M-Pesa number or card you paid with.</li>
    <li>We start the refund within 2 business days of approving it. It usually reaches you within 5 to 10 business days, depending on your bank or mobile money provider.</li>
    <li>The original delivery fee is refunded only when the item was damaged, faulty or wrong.</li>
</ul>

<h2>5. Cancelling an order</h2>
<p>You can cancel an order for a full refund any time before it is dispatched. Contact us as soon as possible with your order number.
Unpaid orders can simply be left unpaid; we may cancel them after 7 days.</p>

<h2>6. Items we cannot take back</h2>
<ul>
    <li>Opened or used products, unless faulty.</li>
    <li>Items returned more than 7 days after delivery.</li>
    <li>Items damaged after delivery through misuse.</li>
</ul>

